/* Input and output of the three open IOCTLs, laid out as in the DDK wmiumkm.h */
typedef struct _WMIOPENGUIDBLOCK
{
    POBJECT_ATTRIBUTES ObjectAttributes;
    ACCESS_MASK DesiredAccess;
    union
    {
        HANDLE Handle;
        ULONG64 Handle64;
    };
} WMIOPENGUIDBLOCK, *PWMIOPENGUIDBLOCK;

/* \WmiGuid\ followed by the 36 character GUID string */
#define WMI_GUID_OBJECT_NAME_LENGTH 45

/* What IOCTL_WMI_GET_VERSION reports */
#define WMI_KERNEL_INTERFACE_VERSION 1

/* Input of IOCTL_WMI_RECEIVE_NOTIFICATIONS, the output is a chain of event WNODEs */
typedef struct _WMI_NOTIFICATION_HANDLES
{
    ULONG HandleCount;
    ULONG Reserved;
    ULONG64 Handles[ANYSIZE_ARRAY];
} WMI_NOTIFICATION_HANDLES, *PWMI_NOTIFICATION_HANDLES;

/* One MOF resource, string offsets count from the start of the list */
typedef struct _WMI_MOF_ENTRY
{
    ULONG RegistryPathOffset;
    ULONG ResourceNameOffset;
    ULONG Flags;
} WMI_MOF_ENTRY, *PWMI_MOF_ENTRY;

/* RegistryPathOffset names an image file rather than a service key */
#define WMI_MOF_ENTRY_IMAGE_PATH 0x00000001

/* Output of IOCTL_WMI_ENUMERATE_MOF_RESOURCES, a lone Count holds the size needed */
typedef struct _WMI_MOF_LIST
{
    ULONG Count;
    WMI_MOF_ENTRY Entries[ANYSIZE_ARRAY];
} WMI_MOF_LIST, *PWMI_MOF_LIST;

/* Input and output of IOCTL_WMI_QUERY_GUID_INFO */
typedef struct _WMI_GUID_INFO_QUERY
{
    union
    {
        HANDLE Handle;
        ULONG64 Handle64;
    };
    BOOLEAN IsExpensive;
} WMI_GUID_INFO_QUERY, *PWMI_GUID_INFO_QUERY;

#define WMI_GUIDTYPE_TRACE  0
#define WMI_GUIDTYPE_DATA   2
#define WMI_GUIDTYPE_EVENT  3

typedef struct _WMI_GUID_PROPERTIES
{
    GUID Guid;
    ULONG GuidType;
    ULONG LoggerId;
    ULONG EnableLevel;
    ULONG EnableFlags;
    BOOLEAN IsEnabled;
} WMI_GUID_PROPERTIES, *PWMI_GUID_PROPERTIES;

/* Output of the two GUID enumeration IOCTLs */
typedef struct _WMI_GUID_LIST
{
    ULONG TotalGuidCount;
    ULONG ReturnedGuidCount;
    WMI_GUID_PROPERTIES Guids[ANYSIZE_ARRAY];
} WMI_GUID_LIST, *PWMI_GUID_LIST;

/* Input and output of IOCTL_WMI_TRANSLATE_FILE_HANDLE */
typedef struct _WMI_FILE_HANDLE_NAME
{
    union
    {
        HANDLE FileHandle;
        ULONG64 FileHandle64;
        ULONG SizeNeeded;
    };
    union
    {
        HANDLE KernelHandle;
        ULONG64 KernelHandle64;
    };
    ULONG BaseIndex;
    USHORT InstanceNameLength;
    WCHAR InstanceNames[ANYSIZE_ARRAY];
} WMI_FILE_HANDLE_NAME, *PWMI_FILE_HANDLE_NAME;
